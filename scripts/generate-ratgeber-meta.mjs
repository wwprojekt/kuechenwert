// One-shot generator: scans src/data/ratgeber/ratgeber-*.ts files,
// extracts the public meta of every RatgeberConfig export, and writes a
// compact ratgeber-meta.ts that the runtime uses to render the overview
// page and to map slugs → lazy data chunks. Re-run when adding a new
// ratgeber data file:
//   node scripts/generate-ratgeber-meta.mjs

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, basename } from "node:path";

const DATA_DIR = join(process.cwd(), "src", "data", "ratgeber");
const OUTPUT_FILE = join(DATA_DIR, "ratgeber-meta.ts");

const files = readdirSync(DATA_DIR)
  .filter((f) => f.startsWith("ratgeber-") && f.endsWith(".ts"))
  .filter(
    (f) =>
      f !== "ratgeber-types.ts" &&
      f !== "ratgeber-index.ts" &&
      f !== "ratgeber-meta.ts",
  )
  .sort();

/** @type {Array<{slug:string,path:string,h1:string,metaDescription:string,category:string,brandName:string|null,dataFile:string}>} */
const entries = [];

for (const file of files) {
  const content = readFileSync(join(DATA_DIR, file), "utf8");
  // Match every "export const NAME: RatgeberConfig = { ... };" block.
  // The configs use no nested template literals so a non-greedy match
  // up to the closing "};" on its own line is reliable.
  const blockRe =
    /export\s+const\s+(\w+)\s*:\s*RatgeberConfig\s*=\s*(\{[\s\S]*?\n\})\s*;/g;
  let match;
  while ((match = blockRe.exec(content)) !== null) {
    const block = match[2];
    const slug = pickString(block, "slug");
    const path = pickString(block, "path");
    const h1 = pickString(block, "h1");
    const metaDescription = pickString(block, "metaDescription");
    const category = pickString(block, "category");
    const brandName = pickString(block, "brandName");
    if (!slug || !path || !h1 || !metaDescription || !category) {
      console.warn(
        `[ratgeber-meta] Skipping ${match[1]} in ${file} – missing required field`,
      );
      continue;
    }
    entries.push({
      slug,
      path,
      h1,
      metaDescription,
      category,
      brandName,
      dataFile: basename(file, ".ts"),
    });
  }
}

entries.sort((a, b) => a.slug.localeCompare(b.slug));

const slugSet = new Set();
for (const e of entries) {
  if (slugSet.has(e.slug)) {
    throw new Error(`Duplicate slug detected: ${e.slug}`);
  }
  slugSet.add(e.slug);
}

const out = `// AUTO-GENERATED by scripts/generate-ratgeber-meta.mjs – do not hand-edit.
// Total entries: ${entries.length}.
// This file is intentionally tiny so it can be loaded eagerly. The full
// RatgeberConfig (sections + faqItems) lives in ratgeber-<group>.ts and
// is loaded on demand via loadRatgeberConfig() in ratgeber-index.ts.

export interface RatgeberMeta {
  slug: string;
  path: string;
  h1: string;
  metaDescription: string;
  category: "brand" | "condition";
  brandName?: string;
  /** Filename (without extension) of the data file that owns the full config. */
  dataFile: string;
}

export const ratgeberMeta: RatgeberMeta[] = ${JSON.stringify(
  entries.map((e) => ({
    slug: e.slug,
    path: e.path,
    h1: e.h1,
    metaDescription: e.metaDescription,
    category: e.category,
    ...(e.brandName ? { brandName: e.brandName } : {}),
    dataFile: e.dataFile,
  })),
  null,
  2,
)};
`;

writeFileSync(OUTPUT_FILE, out, "utf8");
console.log(
  `[ratgeber-meta] Wrote ${entries.length} entries → ${OUTPUT_FILE}`,
);

// Helpers --------------------------------------------------------------

function pickString(block, key) {
  // Field syntax: key: "value", or key: 'value',
  // The values themselves contain no escaped quotes in the existing files
  // (verified). We anchor on the field name + colon + quote.
  const re = new RegExp(`(?:^|\\s|,|\\{)${key}\\s*:\\s*(['"\`])`, "m");
  const m = re.exec(block);
  if (!m) return null;
  const quote = m[1];
  const start = m.index + m[0].length;
  let end = start;
  while (end < block.length) {
    const ch = block[end];
    if (ch === "\\") {
      end += 2;
      continue;
    }
    if (ch === quote) break;
    end++;
  }
  return block.slice(start, end);
}
