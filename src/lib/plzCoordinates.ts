/**
 * Get approximate coordinates for a German postal code.
 * Uses the first 3 digits for lookup.
 * @param postalCode Full or partial postal code (at least 3 digits)
 * @returns Coordinates or null if not found
 */
export function getPlzCoordinates(postalCode: string | null | undefined): PlzCoordinate | null {
  if (!postalCode || postalCode.length < 3) return null;
  const prefix = postalCode.replace(/\s/g, '').substring(0, 3);
  return PLZ_COORDINATES[prefix] || null;
}

/**
 * Anonymize a postal code by showing only the first 3 digits.
 * Example: "80331" -> "803xx"
 * @param postalCode Full postal code
 * @returns Anonymized postal code
 */
export function anonymizePostalCode(postalCode: string | null | undefined): string {
  if (!postalCode || postalCode.length < 3) return 'Unbekannt';
  const clean = postalCode.replace(/\s/g, '');
  return clean.substring(0, 3) + 'xx';
}
